export type TKey = keyof Dict;
const dicts: Record<Lang, Dict> = { en, bn };

const bnDigits = "০১২৩৪৫৬৭৮৯";
export function num(n: number | string, lang: Lang) {
  const s = String(n);
  return lang === "bn" ? s.replace(/\d/g, (d) => bnDigits[+d] ?? d) : s;
}

export function useT() {
  const { lang } = useApp();
  const L: Lang = lang ?? "en";
  const t = (k: TKey, vars?: Record<string, string | number>) => {
    let s = dicts[L][k] ?? en[k];
    if (vars) for (const [v, val] of Object.entries(vars)) s = s.replace(`{${v}}`, num(val, L));
    return s;
  };
  const n = (v: number | string) => num(v, L);
  const date = (iso: string) =>
    new Date(iso + "T00:00:00").toLocaleDateString(L === "bn" ? "bn-BD" : "en-GB", { day: "numeric", month: "short", year: "numeric" });
  return { t, n, date, lang: L };
}
